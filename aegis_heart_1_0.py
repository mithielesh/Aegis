class ODIN_Environment_3D(gym.Env):
    def __init__(self, grid_size, n_obstacles, start_pos, goal_pos, forecasting_model, scaler, initial_sequence):
        super(ODIN_Environment_3D, self).__init__()
        self.grid_size = grid_size
        self.n_obstacles = n_obstacles
        self.start_pos = np.array(start_pos)
        self.goal_pos = np.array(goal_pos)
        self.agent_pos = np.copy(self.start_pos)
        self.forecasting_model = forecasting_model
        self.scaler = scaler
        self.current_sequence = initial_sequence.copy()
        self.action_space = spaces.Discrete(6)
        self.observation_space = spaces.Box(low=0, high=1, shape=(grid_size, grid_size, grid_size), dtype=np.float32)
        self.risk_map = np.zeros((grid_size, grid_size, grid_size))
        self.obstacles = self._generate_dynamic_obstacles()

    def _generate_dynamic_obstacles(self):
        obstacles = []
        for _ in range(self.n_obstacles):
            pos = np.random.randint(0, self.grid_size, size=3)
            size = np.random.randint(2, 5)
            velocity = np.random.uniform(-0.5, 0.5, size=3)
            obstacles.append({'pos': pos.astype(float), 'size': size, 'velocity': velocity})
        return obstacles

    def _update_risk_map(self):
        sequence_reshaped = self.current_sequence.reshape(1, self.current_sequence.shape[0], self.current_sequence.shape[1])
        predicted_scaled_flux = self.forecasting_model.predict(sequence_reshaped, verbose=0)[0, -1, 0]
        dummy_row = np.zeros((1, self.scaler.scale_.shape[0]))
        dummy_row[0, 0] = predicted_scaled_flux
        flux_prediction = self.scaler.inverse_transform(dummy_row)[0, 0]
        base_risk = min(1.0, max(0.1, flux_prediction / 1e-4))
        self.risk_map.fill(0)
        for obs in self.obstacles:
            obs['pos'] += obs['velocity']
            obs['pos'] = np.clip(obs['pos'], 0, self.grid_size - 1)
            x, y, z = obs['pos'].astype(int)
            s = obs['size']
            self.risk_map[max(0, x - s):min(self.grid_size, x + s + 1),
                          max(0, y - s):min(self.grid_size, y + s + 1),
                          max(0, z - s):min(self.grid_size, z + s + 1)] = base_risk
        new_row = self.current_sequence[-1].copy()
        new_row[0] = predicted_scaled_flux
        self.current_sequence = np.vstack([self.current_sequence[1:], new_row])

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)
        self.agent_pos = np.copy(self.start_pos)
        self.obstacles = self._generate_dynamic_obstacles()
        self._update_risk_map()
        return self.risk_map.astype(np.float32), {}

    def step(self, action):
        if action == 0: self.agent_pos[0] -= 1
        elif action == 1: self.agent_pos[0] += 1
        elif action == 2: self.agent_pos[1] -= 1
        elif action == 3: self.agent_pos[1] += 1
        elif action == 4: self.agent_pos[2] -= 1
        elif action == 5: self.agent_pos[2] += 1
        self.agent_pos = np.clip(self.agent_pos, 0, self.grid_size - 1)
        self._update_risk_map()
        terminated = False
        reward = 0
        if np.array_equal(self.agent_pos, self.goal_pos):
            reward = 100
            terminated = True
        agent_risk = self.risk_map[self.agent_pos[0], self.agent_pos[1], self.agent_pos[2]]
        if agent_risk > 0:
            reward = -100
            terminated = True
        reward -= 0.01
        truncated = False
        return self.risk_map.astype(np.float32), reward, terminated, truncated, {}
