import numpy as np
import gymnasium as gym
from gymnasium import spaces
from stable_baselines3 import PPO
import torch
import onnx

print("--- ODIN Agent ONNX Export Utility ---")

# A minimal environment class is needed to load the agent's structure
class GameEnvironment(gym.Env):
    def __init__(self, grid_size=20):
        super(GameEnvironment, self).__init__()
        self.action_space = spaces.Discrete(6)
        self.observation_space = spaces.Box(low=0, high=1, shape=(grid_size, grid_size, grid_size), dtype=np.float32)

# --- EXPORT SETTINGS ---
# Choose which trained agent you want to convert. Options:
# "game_agent_final.zip" (Normal)
# "game_agent_safe.zip" (Cautious)
# "game_agent_aggressive.zip" (Risk-Taker)
AGENT_TO_CONVERT = "game_agent_aggressive.zip"
ONNX_FILENAME = "odin_game_agent_aggressive.onnx"

print(f"\nLoading agent '{AGENT_TO_CONVERT}' for conversion to '{ONNX_FILENAME}'...")

try:
    env = GameEnvironment()
    agent = PPO.load(AGENT_TO_CONVERT, env=env)
    policy_model = agent.policy

    sample_observation = torch.FloatTensor(env.observation_space.sample()).unsqueeze(0)

    torch.onnx.export(
        policy_model,
        sample_observation,
        ONNX_FILENAME,
        opset_version=11,
        input_names=["observation"],
        output_names=["action"],
        dynamic_axes={"observation": {0: "batch_size"}, "action": {0: "batch_size"}}
    )
    print(f"\nSUCCESS! Model has been exported as '{ONNX_FILENAME}'.")
    print("You can now import this file into your Unity project.")

except FileNotFoundError:
    print(f"\nERROR: Could not find the agent file '{AGENT_TO_CONVERT}'.")
    print("Please make sure you have run the correct training script first.")
except Exception as e:
    print(f"\nAn error occurred during export: {e}")